// `bake-osm2world --city <variant>` — the OSM2World higher-fidelity bake (fidelity tier 2), a
// PARALLEL VARIANT of `bake.mjs`: same grid / tileset / runtime contract, richer geometry (every
// S3DB roof shape + real constructions — walls, fences, masts, street lamps, bollards, fountains,
// pylons) reconstructed by OSM2World instead of the footprint extruder.
//
// THE DEFAULT PIPELINE IS UNTOUCHED — bake.mjs, cities/dnipro.json, and public/enriched/dnipro are
// not modified. This writes a SIBLING output dir (cfg.output, e.g. public/enriched/dnipro-o2w) that
// the runtime loads only via the `?enriched=<variant>` A/B compare seam
// (src/lib/globe/enrichedVariant.ts) or an explicit PUBLIC_ENRICHED_TILES_URL.
//
//   node scripts/bake/bake-osm2world.mjs --city dnipro-o2w     (config extends cities/dnipro.json)
//   flags: --refresh (re-extract Overpass XML) · --reconvert (force OSM2World re-runs) · --out <dir>
//
// Pipeline (OSM2WORLD_EXPERIMENT_PREP.md §9 — Slice-1.5 spike verdict VIABLE, browser-VERIFIED):
//   Overpass XML per sub-box (cached) → reference-safe C6 filter (osmXml.mjs) → OSM2World `convert`
//   (heavy modules excluded, ground Y=0, keepOsmElements) → re-bin Building/construction nodes into
//   OUR grid (dedupe across sub-boxes · per-feature contiguous _FEATURE_ID_0 · C6 polygon gate at
//   the centroid) → our instanced trees (vegetation.mjs — same cache + seed as bake.mjs, so an A/B
//   differs ONLY in structures) → REUSED encodeGlb + buildTileset → public/. Ships UNCOMPRESSED
//   (≈1.4× the extruder bake per the spike; weld+draco would give ~23× but needs a DRACOLoader wired
//   into the enriched runtime path — documented upgrade, deliberately NOT done to keep the runtime
//   byte-identical).

